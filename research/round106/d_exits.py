"""D: rules that need new trades - Noise entry cutoff 13:30 / 14:00, square-off 15:00, Noise time stop 45 / 60 min,
15-min channel catastrophic stop 2.5 / 3 ATR. Each set was regenerated by regen.py with that one change."""
import json, os
import r106lib as X
out = {}
print("BASE  " + " | ".join(f"{k} {X.fmt(v)}" for k, v in X.base_grid().items()), flush=True)
Tb = X.load_set("base")[0]
for nm, label in (("ncut1330", "Noise last entry 13:30 (now 14:30)"), ("ncut1400", "Noise last entry 14:00"),
                  ("sq1500", "square-off 15:00 (now 15:15)"), ("ntstop45", "Noise time stop 45 min (< +0.5R)"),
                  ("ntstop60", "Noise time stop 60 min (< +0.5R)"), ("chcat25", "channel catastrophic stop 2.5 ATR"),
                  ("chcat30", "channel catastrophic stop 3 ATR"), ("chcat40", "channel catastrophic stop 4 ATR"),
                  ("chcat50", "channel catastrophic stop 5 ATR")):
    if not os.path.exists(f"/tmp/r106/{nm}.pkl"):
        print("  missing", nm); continue
    T, A, H = X.load_set(nm)
    ch = T.merge(Tb, on=["sym", "date", "entry_time", "strategy"], how="outer", suffixes=("", "_b"), indicator=True)
    diff = ch[(ch._merge != "both") | (ch.exit_time != ch.exit_time_b)]
    print(f"  [{nm}] trades {len(T)} (base {len(Tb)}), changed {len(diff)}, per-lot {T.pnl.sum() - Tb.pnl.sum():+.0f} vs base")
    X.report(label, T, A, H, out)
json.dump(out, open("r106_d.json", "w"), indent=1, default=str)
